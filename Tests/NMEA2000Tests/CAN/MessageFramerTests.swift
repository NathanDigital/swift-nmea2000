  @Test("Frames messages as upstream does", arguments: cases)
  func framesAsUpstream(_ testCase: FramerCase) throws {
    var framer = MessageFramer()
    var frames: [CANFrame] = []
    for message in testCase.messages {
      frames += try framer.frames(for: message)
    }
    #expect(frames == testCase.frames)
  }

  @Test(
    "Rejects PGNs upstream won't send",
    arguments: [59905, 0, 0x4_0000] as [UInt32])
  func rejectsInvalidPGNs(pgn: UInt32) {
    var framer = MessageFramer()
    #expect(throws: FramingError.invalidPGN(pgn)) {
      try framer.frames(for: message(pgn, count: 3, priority: 6))
    }
  }

  @Test func rejectsSourcesOutsideTheBusRange() throws {
    var framer = MessageFramer()
    let message = Message(pgn: 129025, source: 252, data: [1, 2, 3])
    #expect(throws: FramingError.invalidSource(252)) { try framer.frames(for: message) }
    // An address claim may come from the null address.
    let claim = Message(pgn: 60928, source: 254, data: [UInt8](repeating: 0, count: 8))
    #expect(try framer.frames(for: claim).count == 1)
  }

  @Test func rejectsPayloadsLongerThanAFastPacket() {
    var framer = MessageFramer()
    #expect(throws: FramingError.payloadTooLong(224)) {
      try framer.frames(for: message(129029, count: 224, priority: 3))
    }
  }

  @Test func padsShortFastPacketsWithNotAvailable() throws {
