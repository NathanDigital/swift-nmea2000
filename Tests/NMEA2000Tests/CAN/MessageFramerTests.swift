/// Messages sent in order through one framer, and the frames upstream's node
/// sends for them, from `scripts/upstream-vectors "Frames send"`. The harness
/// node's address is 23.
struct FramerCase: Sendable, CustomTestStringConvertible {
  var name: String
  var messages: [Message]
  var frames: [CANFrame]

  init(_ name: String, messages: [Message], frames: [CANFrame]) {
    self.name = name
    self.messages = messages
    self.frames = frames
  }

  var testDescription: String { name }
}

/// A message from the harness's node: payload bytes counting up from `first`.
private func message(
  _ pgn: UInt32, count: Int, priority: UInt8, destination: UInt8 = Message.broadcastAddress,
  first: UInt8 = 0
) -> Message {
  Message(
    pgn: pgn, priority: priority, source: 23, destination: destination,
    data: (0..<count).map { first &+ UInt8($0) })
}

