  @Test("Decodes upstream bytes", arguments: vectors.indices)
  func decodes(index: Int) throws {
    let (value, bytes) = Self.vectors[index]
    try expectDecodes(bytes, as: Self.decodedValues[index] ?? value)
  }

  @Test func toleratesShortPayloadsAndRejectsOtherPGNs() {
    expectTolerantDecoding(WaypointList.self, from: Self.vectors[0].1)
  }

  @Test func saysHowManyWaypointsAreSent() {
    // The message fills after nine of the waypoints.
    let full = Self.vectors[1].0
    #expect(full.waypoints.count > 9)
    #expect(full.sentWaypointCount == 9)
  }
